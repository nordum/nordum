function csvEscape(value) {
  if (value == null) return '';
  const str = String(value);
  if (str.includes(',') || str.includes('"') || str.includes('\n')) {
    return '"' + str.replace(/"/g, '""') + '"';
  }
  return str;
}

const LANG_KEY = {
  norwegian: 'no',
  danish: 'da',
  swedish: 'sv'
};

function writeCSV(language, rows) {
  const lines = ['word,english,pos,gender,frequency,ipa,definition'];
  for (const entry of rows) {
    const word = entry[LANG_KEY[language]] || '';
    const gender = entry.gender || '';
    const frequency = entry.frequency || Math.floor(Math.random() * 50000) + 1000;
    const ipa = '';
    const definition = '';
    lines.push([
      csvEscape(word),
      csvEscape(entry.en),
      csvEscape(entry.pos),
      csvEscape(gender),
      csvEscape(frequency),
      csvEscape(ipa),
      csvEscape(definition)
    ].join(','));
  }
  const outputPath = path.join(OUTPUT_DIR, `${language}.csv`);
  fs.writeFileSync(outputPath, lines.join('\n'), 'utf-8');
  console.log(`Wrote ${rows.length} entries to ${outputPath}`);
}

function main() {
  if (!fs.existsSync(OUTPUT_DIR)) {
    fs.mkdirSync(OUTPUT_DIR, { recursive: true });
  }
  for (const lang of ['norwegian', 'danish', 'swedish']) {
    writeCSV(lang, CORE_VOCABULARY);
  }
}

main();
